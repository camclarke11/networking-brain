from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HANDLE = "theoryofbehaviour"
DATA = ROOT / "data" / HANDLE
TRANSCRIPTS = ROOT / "examples" / HANDLE
WHAT_PERFORMS = ROOT / "knowledge" / "00-what-performs.md"
TAG_FIELDS = ["id", "category", "tier", "format", "hook", "named_tool", "proof", "objection",
              "character", "ending", "cta", "reupload_of", "notes"]
TOO_NEW_DAYS = 7
AUTO_START = "<!-- AUTO:START @theoryofbehaviour (generated by tools/performance.py report; edits here are overwritten) -->"
AUTO_END = "<!-- AUTO:END @theoryofbehaviour -->"
ID_RE = re.compile(r"instagram\.com/(?:reel|p)/([A-Za-z0-9_-]+)")


def use_account(handle):
    """Point every path at one account's folders."""
    global HANDLE, DATA, TRANSCRIPTS, AUTO_START, AUTO_END, TOO_NEW_DAYS
    HANDLE = handle.lstrip("@").strip().lower()
    TOO_NEW_DAYS = read_config().get("too_new_days", {}).get(HANDLE, 7)
    DATA = ROOT / "data" / HANDLE
    TRANSCRIPTS = ROOT / "examples" / HANDLE
    AUTO_START = f"<!-- AUTO:START @{HANDLE} (generated by tools/performance.py report; edits here are overwritten) -->"
    AUTO_END = f"<!-- AUTO:END @{HANDLE} -->"


def read_config():
    config = ROOT / "config.json"
    return json.loads(config.read_text(encoding="utf-8")) if config.exists() else {}


def default_account():
    return read_config().get("default_account") or HANDLE


def clean_transcript(text):
    """Drop auto-transcription junk: looping phrases, run-on garbage and noise after long silences."""
    text = re.split(r"\n\s*\n\s*\n\s*\n\s*\n", text.strip())[0]
    keep = []
    for line in text.splitlines():
        words = line.split()
        if any(len(w) > 40 for w in words):
            continue
        if len(words) > 30 and len(set(words)) / len(words) < 0.2:
            continue
        keep.append(line.rstrip())
    return "\n".join(keep).strip()


# ---------- loading ----------

def read_csv(path):
    if not path.exists():
        return []
    with path.open(encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def write_csv(path, rows, fields):
    tmp = path.with_suffix(".tmp")
    with tmp.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)
    tmp.replace(path)


def num(value):
    if value in (None, ""):
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def parse_time(value):
    if not value:
        return None
    try:
        return datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return None


def load_transcripts():
    """Map post ID -> (file name, spoken text) from examples/transcripts headers."""
    out = {}
    for path in sorted(TRANSCRIPTS.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        header = "\n".join(line for line in text.splitlines()[:6] if line.startswith("<!--"))
        match = ID_RE.search(header)
        if not match:
            continue
        body = "\n".join(line for line in text.splitlines() if not line.startswith("<!--")).strip()
        out[match.group(1)] = (path.name, body)
    return out


def load_tags():
    return {row["id"]: row for row in read_csv(DATA / "post-tags.csv")}


def load_posts():
    videos = read_csv(DATA / "videos.csv")
    features = {r.get("video_id"): r for r in read_csv(DATA / "video-features.csv")}
    history = read_csv(DATA / "video-history.csv")
    tags = load_tags()
    transcripts = load_transcripts()
    now = max((parse_time(r.get("captured_at")) for r in history if r.get("captured_at")),
              default=None) or datetime.now(timezone.utc)

    by_video = {}
    for row in history:
        by_video.setdefault(row.get("video_id"), []).append(row)

    posts = []
    for v in videos:
        pid = v.get("id")
        f = features.get(pid, {})
        published = parse_time(v.get("published_at"))
        age = (now - published).total_seconds() / 86400 if published else None
        obs = sorted(by_video.get(pid, []), key=lambda r: r.get("captured_at") or "")
        velocity = None
        if len(obs) >= 2:
            a, b = obs[-2], obs[-1]
            ta, tb = parse_time(a["captured_at"]), parse_time(b["captured_at"])
            va, vb = num(a.get("view_count")), num(b.get("view_count"))
            if ta and tb and va is not None and vb is not None and tb > ta:
                velocity = (vb - va) / ((tb - ta).total_seconds() / 86400)
        views = num(v.get("view_count"))
        likes = num(v.get("like_count"))
        hidden = str(v.get("counts_hidden", "")).lower() == "true"
        # Many rows show exactly 3 likes on thousands of views: withheld counts, not real ones.
        likes_suspect = hidden or (likes is not None and likes <= 3 and (views or 0) >= 1000)
        transcript_file, text = transcripts.get(pid, (None, ""))
        duration = num(v.get("duration_seconds")) or num(f.get("duration_seconds"))
        posts.append({
            "id": pid, "url": v.get("url"), "title": (v.get("title") or "").split("#")[0].strip(),
            "caption": v.get("caption") or "", "published": published, "age_days": age,
            "views": views, "likes": None if likes_suspect else likes, "likes_suspect": likes_suspect,
            "comments": num(v.get("comment_count")), "reposts": num(v.get("repost_count")),
            "duration": duration, "velocity_per_day": velocity, "observations": len(obs),
            "tags": tags.get(pid, {}), "transcript_file": transcript_file, "text": text,
            "hashtags": v.get("hashtags") or "",
            "audio_title": v.get("audio_title") or "", "audio_type": v.get("audio_type") or "",
            "collaborators": v.get("collaborators") or "",
        })
    for p in posts:
        p.update(text_features(p))
    return posts, now


# ---------- automatic features ----------

def title_pattern(title):
    """How the caption's first line (the on-screen title) is framed."""
    t = title.strip().lower()
    if re.match(r"^save this", t):
        return "Save this…"
    if re.match(r"^(stop|never|don't|quit)\b", t):
        return "contrarian order"
    if re.match(r"^(how to|here's how|try it)", t):
        return "how-to"
    if t.endswith("?") or re.match(r"^(why|what|who|which)\b", t):
        return "question"
    if re.search(r"\b(research|study|studies|researchers|psychologist)\b", t):
        return "research claim"
    if re.match(r"^(the|nobody|your|you|logic|sometimes)\b", t):
        return "statement"
    return "other"


def opening_type(text):
    """The spoken first line, mapped to the hook codes in knowledge/03-hooks.md."""
    first = text.strip().split("\n")[0].strip().lower()
    if re.match(r"^(when|if) you\b", first):
        return "N1 situation + order"
    if re.match(r"^(so, )?\"?(what do you do|can i pick|hi, nice)", first) or "is why" in first[:80]:
        return "N2 the line you say"
    if re.match(r"^(stop|never|don't|quit)\b", first):
        return "N3 contrarian order"
    if re.match(r"^how to\b", first):
        return "N4 how-to promise"
    if re.match(r"^the (real reason|first thing|reason)", first):
        return "N5 hidden cause"
    if re.search(r"\b(in (\w+ )?(steps|seconds|words))\b", first) or re.match(r"^make (anyone|people)", first):
        return "N7 steps promise"
    if re.match(r"^(the|logic|your|nobody|people)\b", first):
        return "N6 bold claim"
    return "other"


def text_features(p):
    text = p["text"]
    words = re.findall(r"[\w'’$£]+", text)
    n = len(words)
    lower = text.lower()
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    last = lines[-1] if lines else ""
    return {
        "words": n or None,
        "wpm": round(n / p["duration"] * 60) if n and p["duration"] else None,
        "opening": (lines[0][:140] if lines else ""),
        "opening_type": opening_type(text) if text else "",
        "title_pattern": title_pattern(p["title"]),
        "title_has_number": bool(re.search(r"\d", p["title"])),
        "and_then": len(re.findall(r"\band then\b", lower)),
        "but_so_per_100": round(100 * len(re.findall(r"\b(but|so)\b", lower)) / n, 1) if n else None,
        "you_per_100": round(100 * len(re.findall(r"\byou(r|'re|'ve|'ll|'d)?\b", lower)) / n, 1) if n else None,
        "voiced_objection": bool(re.search(r"you're (probably )?thinking|i know,? you're|you might think", lower)),
        "cites_study": bool(re.search(r"\b(19|20)\d\d\b.*\b(study|researchers|psychologists)|\b(study|researchers|psychologists)\b", lower)),
        "share_cta": bool(re.search(r"\bsend this to\b", lower[-300:])),
        "ends_with_question": last.endswith("?"),
        "length_bucket": bucket_words(n) if n else "unknown",
    }


def bucket_words(n):
    for limit, label in ((100, "<100 words"), (130, "100–129 words"), (160, "130–159 words"), (190, "160–189 words")):
        if n < limit:
            return label
    return "190+ words"


def detect_reuploads(posts):
    """Suggest reupload_of for near-identical transcripts (earlier post wins)."""
    ordered = sorted((p for p in posts if p["text"]), key=lambda p: p["published"] or datetime.min.replace(tzinfo=timezone.utc))
    found = {}
    for i, p in enumerate(ordered):
        for q in ordered[:i]:
            if difflib.SequenceMatcher(None, p["text"][:1500], q["text"][:1500]).quick_ratio() < 0.8:
                continue
            if difflib.SequenceMatcher(None, p["text"][:1500], q["text"][:1500]).ratio() >= 0.8:
                found[p["id"]] = q["id"]
                break
    return found


# ---------- statistics ----------

def median(values):
    values = [v for v in values if v is not None]
    return statistics.median(values) if values else None


def mature(posts):
    return [p for p in posts if p["age_days"] is None or p["age_days"] >= TOO_NEW_DAYS]


def rate(p, key):
    return (p[key] / p["views"] * 100) if p.get(key) is not None and p["views"] else None


def group_table(posts, key_fn, min_n=1):
    groups = {}
    for p in posts:
        key = key_fn(p)
        if key in (None, ""):
            continue
        groups.setdefault(key, []).append(p)
    rows = []
    for key, items in groups.items():
        if len(items) < min_n:
            continue
        rows.append({
            "group": key, "n": len(items),
            "median": median([p["views"] for p in items]),
            "best": max((p["views"] or 0) for p in items),
            "share": sum((p["views"] or 0) for p in items),
        })
    return sorted(rows, key=lambda r: -(r["median"] or 0))


def fmt(n, digits=0):
    if n is None:
        return "—"
    if abs(n) >= 1_000_000:
        return f"{n / 1_000_000:.2f}M"
    if abs(n) >= 10_000:
        return f"{n / 1000:.0f}k"
    if abs(n) >= 1000:
        return f"{n / 1000:.1f}k"
    return f"{n:.{digits}f}"


def percentile(value, values):
    values = [v for v in values if v is not None]
    if value is None or not values:
        return None
    return round(100 * sum(v <= value for v in values) / len(values))


