#!/usr/bin/env python3
"""Performance analysis for our account and the accounts we study, built on Media Tools exports.

Adapted from the zlliott-brain tool. Standard library only. Every account lives in its
own folder: data/<handle>/ for numbers and labels, examples/<handle>/ for transcripts.

  [--account HANDLE] import <export folder or .zip>   Merge an export (handle read from its account.json)
  [--account HANDLE] tag                              List posts that still need labels
  [--account HANDLE] report                           Rebuild that account's live tables in knowledge/00-what-performs.md
  [--account HANDLE] post <id or instagram url>       Full breakdown of one post against its account
  [--account HANDLE] breakdowns                       Write data/<handle>/post-breakdowns.md
  accounts                                           List the accounts we have data for

Without --account, commands use "default_account" from config.json.
Content labels come from data/<handle>/post-tags.csv, written with the taxonomy in
knowledge/00-what-performs.md. Everything reported is correlation, not cause.
"""
