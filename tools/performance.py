def cmd_import(source):
    src = Path(source).expanduser()
    with tempfile.TemporaryDirectory() as tmp:
        if src.suffix == ".zip":
            with zipfile.ZipFile(src) as z:
                z.extractall(tmp)
            candidates = list(Path(tmp).rglob("videos.csv"))
            if not candidates:
                sys.exit("No videos.csv found in that zip.")
            src = candidates[0].parent
        if not (src / "videos.csv").exists():
            sys.exit(f"No videos.csv in {src}. Point this at a Media Tools account export folder.")
        if (src / "account.json").exists():
            handle = json.loads((src / "account.json").read_text(encoding="utf-8")).get("account", {}).get("handle")
            if handle and not EXPLICIT_ACCOUNT:
                use_account(handle)
        DATA.mkdir(parents=True, exist_ok=True)
        TRANSCRIPTS.mkdir(parents=True, exist_ok=True)
        for name in ("videos.csv", "video-features.csv", "account.json", "snapshots.csv"):
            if (src / name).exists():
                shutil.copy2(src / name, DATA / name)
        # History accumulates across exports instead of being replaced.
        old = read_csv(DATA / "video-history.csv")
        new = read_csv(src / "video-history.csv")
        if new or old:
            fields = list(dict.fromkeys([*(new[0].keys() if new else []), *(old[0].keys() if old else [])]))
            merged = {(r.get("video_id"), r.get("captured_at")): r for r in old}
            merged.update({(r.get("video_id"), r.get("captured_at")): r for r in new})
            write_csv(DATA / "video-history.csv",
                      sorted(merged.values(), key=lambda r: (r.get("video_id") or "", r.get("captured_at") or "")),
                      fields)
        added = import_transcripts(src)
    posts, _ = load_posts()
    untagged = [p for p in posts if not p["tags"]]
    print(f"Imported {len(posts)} posts for @{HANDLE} into data/{HANDLE}/. New transcripts added: {added}.")
    print(f"Posts still needing labels in data/post-tags.csv: {len(untagged)}"
          + (" (run: python3 tools/performance.py tag)" if untagged else ""))


def import_transcripts(src):
    """Copy export transcripts (TXT) for posts that don't have one yet."""
    have = set(load_transcripts())
    manifest = {}
    if (src / "manifest.json").exists():
        for asset in json.loads((src / "manifest.json").read_text(encoding="utf-8")).get("assets", []):
            txt = [f for f in asset.get("transcript_files", []) if f.endswith(".txt")]
            if txt:
                manifest[asset["id"]] = (asset.get("url", ""), src / txt[0])
    videos = {v["id"]: v for v in read_csv(src / "videos.csv")}
    # Some exports ship transcripts as loose files named "... [<post id>].txt".
    for path in src.rglob("*.txt"):
        found = re.search(r"\[([A-Za-z0-9_-]+)\]", path.name)
        if found and found.group(1) in videos and found.group(1) not in manifest:
            manifest[found.group(1)] = (videos[found.group(1)].get("url", ""), path)
    numbers = [int(m.group(1)) for m in (re.match(r"(\d+)-", p.name) for p in TRANSCRIPTS.glob("*.md")) if m]
    next_no = max(numbers, default=0) + 1
    added = 0
    ordered = sorted(manifest.items(), key=lambda kv: videos.get(kv[0], {}).get("published_at", ""))
    for pid, (url, path) in ordered:
        if pid in have or not path.exists():
            continue
        v = videos.get(pid, {})
        title = (v.get("title") or pid).split("#")[0].strip()
        slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:60] or pid.lower()
        text = clean_transcript(path.read_text(encoding="utf-8"))
        header = (f"<!-- #{next_no:02d} | posted {(v.get('published_at') or '')[:10]} | "
                  f"{fmt(num(v.get('view_count')))} views at import | {len(text.split())} words -->\n"
                  f"<!-- Title/caption: {(v.get('caption') or title).replace(chr(10), ' / ')} -->\n"
                  f"<!-- {url or v.get('url', '')} | @{HANDLE} | Auto-transcribed; NOT fact-checked. Use for structure only, never copy. -->\n\n")
        (TRANSCRIPTS / f"{next_no:02d}-{slug}.md").write_text(header + text + "\n", encoding="utf-8")
        next_no += 1
        added += 1
    return added


def cmd_tag():
    posts, _ = load_posts()
    reuploads = detect_reuploads(posts)
    todo = [p for p in posts if not p["tags"]]
    if not todo:
        print("Every post has labels in data/post-tags.csv.")
        return
    print(f"{len(todo)} post(s) need a row in data/post-tags.csv. Columns: {','.join(TAG_FIELDS)}")
    print(f"File: data/{HANDLE}/post-tags.csv. Label values are defined in knowledge/00-what-performs.md → 'Label taxonomy'.\n")
    for p in sorted(todo, key=lambda p: p["published"] or datetime.min.replace(tzinfo=timezone.utc)):
        print(f"- {p['id']} | {(p['published'] or datetime.min).date()} | {fmt(p['views'])} views | {p['title'][:70]}")
        print(f"  opening: {p['opening'] or '(no transcript yet)'}")
        if p["id"] in reuploads:
            print(f"  looks like a re-upload of {reuploads[p['id']]}")


def cmd_report():
    posts, now = load_posts()
    if not posts:
        sys.exit(f"No data for @{HANDLE}. Run: python3 tools/performance.py import <Media Tools export>")
    m = mature(posts)
    acct_median = median([p["views"] for p in m])
    total = sum(p["views"] or 0 for p in posts)
    ranked = sorted(posts, key=lambda p: -(p["views"] or 0))
    untagged = [p for p in posts if not p["tags"]]
    out = [AUTO_START, "", f"## Live data: @{HANDLE}", "",
           f"_Data as of {now.date()} · {len(posts)} posts · {fmt(total)} total views · "
           f"median {fmt(acct_median)}" + (f" (posts at least {TOO_NEW_DAYS} days old)" if TOO_NEW_DAYS else " (all posts; one export, so newer posts have had less time)") + " · "
           f"{len(untagged)} post(s) unlabelled_", ""]

    def section(title, rows, note=""):
        out.extend([f"### @{HANDLE}: {title}", ""])
        if note:
            out.extend([note, ""])
        out.extend(["| Group | Posts | Median views | Best | Share of views |", "|---|---|---|---|---|"])
        for r in rows:
            flag = " ⚠️ n<3" if r["n"] < 3 else ""
            out.append(f"| {r['group']}{flag} | {r['n']} | {fmt(r['median'])} | {fmt(r['best'])} | "
                       f"{100 * r['share'] / total:.0f}% |" if total else "")
        out.append("")

    tag = lambda k: (lambda p: p["tags"].get(k) or None)
    originals = [p for p in m if not p["tags"].get("reupload_of")]
    section("By content category", group_table(originals, tag("category")),
            "Re-uploads excluded. Categories and tiers come from post-tags.csv.")
    section("By topic tier", group_table(originals, lambda p: f"Tier {p['tags']['tier']}" if p["tags"].get("tier") else None))
    section("By format", group_table(originals, tag("format")),
            "Format codes F1–F6 are defined in knowledge/06-formats.md.")
    section("By hook", group_table(originals, tag("hook")),
            "Hook codes N1–N8 are defined in knowledge/03-hooks.md.")
    section("Named tool or acronym?", group_table(originals, tag("named_tool")))
    section("By proof type", group_table(originals, tag("proof")))
    section("Objection voiced?", group_table(originals, tag("objection")))
    section("Named character?", group_table(originals, tag("character")))
    section("By ending", group_table(originals, tag("ending")))
    section("By call to action", group_table(originals, tag("cta")))
    section("By title pattern (automatic)", group_table(originals, lambda p: p["title_pattern"]))
    section("By spoken opening (automatic)", group_table(originals, lambda p: p["opening_type"] or None))
    section("By length (automatic)", group_table(originals, lambda p: p["length_bucket"]))
    section("By weekday posted (UTC)", group_table(originals, lambda p: p["published"].strftime("%A") if p["published"] else None))

    out.extend([f"### @{HANDLE}: every post, ranked", "",
                "| # | Views | vs median | Age (days) | Views/day lately | Title | Category | Hook | File |",
                "|---|---|---|---|---|---|---|---|---|"])
    for i, p in enumerate(ranked, 1):
        vs = f"{p['views'] / acct_median:.1f}×" if p["views"] and acct_median else "—"
        new = " 🆕" if p["age_days"] is not None and p["age_days"] < 7 else ""
        out.append(f"| {i} | {fmt(p['views'])} | {vs} | {p['age_days']:.0f}{new} | {fmt(p['velocity_per_day'])} | "
                   f"{p['title'][:60].replace('|', '/')} | {p['tags'].get('category', '❓')} | "
                   f"{p['tags'].get('hook', '')} | `{(p['transcript_file'] or '')[:2]}` |")
    out.extend(["", f"_🆕 = under 7 days old{', excluded from medians' if TOO_NEW_DAYS else ''}. 'Views/day lately' uses the last two "
                "tracking snapshots. Likes are omitted where Instagram withholds them._", "", AUTO_END])
    block = "\n".join(line for line in out if line is not None)

    text = WHAT_PERFORMS.read_text(encoding="utf-8") if WHAT_PERFORMS.exists() else "# 00 — What Actually Performs\n"
    if AUTO_START in text and AUTO_END in text:
        text = text[:text.index(AUTO_START)] + block + text[text.index(AUTO_END) + len(AUTO_END):]
    else:
        text = text.rstrip() + "\n\n---\n\n" + block + "\n"
    WHAT_PERFORMS.write_text(text, encoding="utf-8")

    summary = [{k: (v.isoformat() if isinstance(v, datetime) else v) for k, v in p.items() if k != "text"}
               for p in ranked]
    (DATA / "performance.json").write_text(json.dumps({"generated": now.isoformat(), "median_views": acct_median,
                                                       "posts": summary}, indent=1), encoding="utf-8")
    print(f"Updated {WHAT_PERFORMS.relative_to(ROOT)} (@{HANDLE} section) and data/{HANDLE}/performance.json.")
    if untagged:
        print(f"{len(untagged)} post(s) are unlabelled and missing from the grouped tables. Run: python3 tools/performance.py tag")


def cmd_post(ref):
    posts, now = load_posts()
    match = ID_RE.search(ref)
    pid = match.group(1) if match else ref.strip().strip("/")
    p = next((x for x in posts if x["id"] == pid), None)
    if not p:
        sys.exit(f"{pid} isn't in data/{HANDLE}/. Import a newer Media Tools export, or pass --account.")
    m = mature(posts)
    views = [x["views"] for x in m]
    acct_median = median(views)
    cat = p["tags"].get("category")
    peers = [x for x in m if x["tags"].get("category") == cat and x["id"] != p["id"]
             and not x["tags"].get("reupload_of")] if cat else []
    cat_median = median([x["views"] for x in peers])

    def line(label, value):
        print(f"- **{label}:** {value}")

    print(f"## {p['title'] or p['id']}\n")
    print(p["url"], "\n")
    line("Posted", f"{p['published'].date() if p['published'] else '?'} ({p['age_days']:.0f} day{'' if round(p['age_days']) == 1 else 's'} ago)"
         + (" — too new to judge fairly" if p['age_days'] is not None and p['age_days'] < TOO_NEW_DAYS else ""))
    line("Views", f"{fmt(p['views'])} · {percentile(p['views'], views)}th percentile · "
         + (f"{p['views'] / acct_median:.1f}× the account median ({fmt(acct_median)})" if p["views"] and acct_median else "no median yet"))
    if cat:
        line("Category", f"{cat} (tier {p['tags'].get('tier', '?')}) · category median {fmt(cat_median)} across {len(peers)} other original post(s)")
    line("Recent growth", f"{fmt(p['velocity_per_day'])} views/day between the last two snapshots"
         if p["velocity_per_day"] is not None else "not enough tracking snapshots yet")
    for key, label in (("likes", "Like rate"), ("comments", "Comment rate"), ("reposts", "Share/repost rate")):
        r = rate(p, key)
        acct = median([rate(x, key) for x in m])
        line(label, f"{r:.2f}% (account median {acct:.2f}%)" if r is not None and acct else
             ("hidden or withheld by Instagram" if key == "likes" and p["likes_suspect"] else "unknown"))
    line("Length", f"{p['duration']:.0f}s · {p['words'] or '?'} words · {p['wpm'] or '?'} wpm" if p["duration"] else "unknown")
    if p["audio_title"] or p["collaborators"]:
        line("Audio / collabs", f"{p['audio_title'] or '—'} ({p['audio_type'] or '?'}) · {p['collaborators'] or 'no collaborators'}")
    print("\n**Labels:** " + (", ".join(f"{k}={v}" for k, v in p["tags"].items() if v and k not in ("id", "notes"))
                              or "none yet (add to data/post-tags.csv)"))
    print(f"\n**Packaging & structure (automatic):** title pattern *{p['title_pattern']}* · opening *{p['opening_type'] or '—'}* · "
          f"'and then' ×{p['and_then']} · but/so per 100 words {p['but_so_per_100']} · 'you' per 100 words {p['you_per_100']} · "
          f"objection voiced: {'yes' if p['voiced_objection'] else 'no'} · cites a study: {'yes' if p['cites_study'] else 'no'} · "
          f"share CTA: {'yes' if p['share_cta'] else 'no'}")
    print(f"\n**Opening line:** “{p['opening']}”" if p["opening"] else "\n**Opening line:** no transcript")

    # Hypotheses: compare this post's labels to how each label value performs.
    originals = [x for x in m if not x["tags"].get("reupload_of")]
    findings = []
    checks = [("category", "category"), ("tier", "topic tier"), ("format", "format"), ("hook", "hook"),
              ("named_tool", "named tool"), ("proof", "proof"), ("objection", "objection voiced"),
              ("character", "named character"), ("ending", "ending"), ("cta", "call to action")]
    for key, label in checks:
        value = p["tags"].get(key)
        if not value:
            continue
        same = [x["views"] for x in originals if x["tags"].get(key) == value and x["id"] != p["id"]]
        if len(same) >= 2 and acct_median:
            ratio = median(same) / acct_median
            findings.append((ratio, f"{label} = {value}: similar posts get {ratio:.1f}× the account median (n={len(same)})"))
    for key, label, value in (("title_pattern", "title pattern", p["title_pattern"]),
                              ("opening_type", "spoken opening", p["opening_type"])):
        same = [x["views"] for x in originals if x[key] == value and x["id"] != p["id"]]
        if value and len(same) >= 2 and acct_median:
            ratio = median(same) / acct_median
            findings.append((ratio, f"{label} = {value}: similar posts get {ratio:.1f}× the account median (n={len(same)})"))
    if p["tags"].get("reupload_of"):
        findings.append((0.5, f"re-upload of {p['tags']['reupload_of']}: re-uploads usually underperform the original"))
    if findings:
        print("\n**Likely working for it:**")
        for ratio, text in sorted(findings, reverse=True):
            if ratio >= 1.2:
                print(f"- {text}")
        print("\n**Likely holding it back:**")
        for ratio, text in sorted(findings):
            if ratio < 0.8:
                print(f"- {text}")
    print("\n_Patterns are correlations across this account's posts, not proof of cause. Small groups (n<3) are weak evidence._")


def cmd_breakdowns():
    """One readable file with every post's breakdown, for chat apps that can't run this tool."""
    import contextlib
    import io
    posts, now = load_posts()
    newest = sorted(posts, key=lambda p: p["published"] or datetime.min.replace(tzinfo=timezone.utc), reverse=True)
    parts = [f"# Post breakdowns for @{HANDLE}\n\n_Generated {now.date()} by tools/performance.py from the latest "
             f"Media Tools data. Newest first. Numbers are public Instagram stats; labels come from data/post-tags.csv._\n"]
    for p in newest:
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            cmd_post(p["id"])
        parts.append(buf.getvalue().replace("## ", "## ", 1))
    (DATA / "post-breakdowns.md").write_text("\n---\n\n".join(parts), encoding="utf-8")
    print(f"Wrote data/{HANDLE}/post-breakdowns.md ({len(posts)} posts).")


